CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username NVARCHAR(30) NOT NULL CONSTRAINT UQ_Users_Username UNIQUE,
    email NVARCHAR(100) NOT NULL,
    role NVARCHAR(15) NOT NULL CHECK (role IN ('USER','CREATOR','ADMIN')),
    rate_per_post DECIMAL(18,2) NOT NULL CHECK (rate_per_post > 0),
    max_daily_posts INT NOT NULL CHECK (max_daily_posts BETWEEN 1 AND 10),
    level INT NOT NULL CHECK (level >= 1),
    status NVARCHAR(15) NOT NULL CHECK (status IN ('ACTIVE','SUSPENDED','DEACTIVATED'))
);
CREATE TABLE posts (
    post_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_name NVARCHAR(100) NOT NULL,
    advertiser_email NVARCHAR(100) NOT NULL,
    advertiser_phone NVARCHAR(20) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL CHECK (end_date > start_date),
    number_of_posts INT NOT NULL CHECK (number_of_posts >= 1),
    total_cost DECIMAL(18,2) NOT NULL CHECK (total_cost >= 0),
    status NVARCHAR(15) NOT NULL CHECK (status IN ('DRAFT','SCHEDULED','PUBLISHED','CANCELLED')),
    user_id INT NOT NULL REFERENCES users(user_id)
);
